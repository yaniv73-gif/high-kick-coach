function withMediaOverride(exercise: Exercise): Exercise {
  const override = EXERCISE_MEDIA_OVERRIDES[exercise.id]
  return override ? { ...exercise, image: override.image ?? exercise.image, video: override.video ?? exercise.video } : exercise
}

export function getExerciseById(id: string): Exercise | undefined {
  const exercise = EXERCISES.find((e) => e.id === id)
  return exercise ? withMediaOverride(exercise) : undefined
}

export function getAllExercisesResolved(): Exercise[] {
  return EXERCISES.map(withMediaOverride)
}
